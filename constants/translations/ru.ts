/** Russian has three plural forms: 1 задача, 2 задачи, 5 задач (21 задача, 11 задач). */
const plural = (count: number, one: string, few: string, many: string) => {
  const n = Math.abs(Math.trunc(count));
  const ten = n % 10;
  const hundred = n % 100;
  if (ten === 1 && hundred !== 11) return one;
  if (ten >= 2 && ten <= 4 && (hundred < 12 || hundred > 14)) return few;
  return many;
};

const TRIAL_UNITS: Record<TrialUnit, [one: string, few: string, many: string]> = {
  day: ["день", "дня", "дней"],
  week: ["неделя", "недели", "недель"],
  month: ["месяц", "месяца", "месяцев"],
  year: ["год", "года", "лет"],
};
/** "на 7 дней" — the accusative after "на" matches these forms, except "неделю". */
const trialLength = (count: number, unit: TrialUnit) =>
  `${count} ${unit === "week" ? plural(count, "неделю", "недели", "недель") : plural(count, ...TRIAL_UNITS[unit])}`;

type ShiftUnit = "minutes" | "hours" | "days" | "weeks" | "months";
const shiftUnit = (size: number, unit: ShiftUnit) =>
  ({
    minutes: plural(size, "минуту", "минуты", "минут"),
    hours: plural(size, "час", "часа", "часов"),
    days: plural(size, "день", "дня", "дней"),
    weeks: plural(size, "неделю", "недели", "недель"),
    months: plural(size, "месяц", "месяца", "месяцев"),
  })[unit];

const tasks = (n: number) => `${n} ${plural(n, "задача", "задачи", "задач")}`;
/** The accusative, after a verb: "отметить 1 задачу". */
